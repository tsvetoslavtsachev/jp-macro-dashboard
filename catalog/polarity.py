# Provenance на всяка OPT зона — машинно четимият близнак на данни-паса.
# ПРАЗНО в v1: няма зони без емпиричен пас (фаза 6). Механизмът се пази.
OPT_PROVENANCE: dict[str, str] = {}

# Кога и как са фиксирани зоните — един стринг, цитиран от лицето и експорта.
OPT_SOURCE_NOTE = (
    "JP v1 няма оптимални зони: всички полярности са линейни до данни-паса на "
    "фаза 6 (приемен гейт: балонната ера 1985-90 свети, спокойна епоха мълчи). "
    "Температурният слой дотогава законно брои 0/0."
)

# Multi-lens override (лещово-специфична полярност). Празно за JP — всяка
# серия живее в точно една леща. Механизмът се пази заради фамилния паритет.
POLARITY_BY_LENS: dict[tuple[str, str], Any] = {}

# Peer-group тегла. Групите са по 1-2 серии → всички 1.0 (фамилен мандат №38
# §А3). Механизмът се пази, за да не се преправя агрегацията по-късно.
PEER_GROUP_WEIGHT: dict[str, float] = {}


def polarity_for(key: str, lens: str | None = None) -> Any:
    """Полярността на серия (по избор — в контекста на конкретна леща)."""
    if lens is not None and (lens, key) in POLARITY_BY_LENS:
        return POLARITY_BY_LENS[(lens, key)]
    return POLARITY.get(key, +1)


def peer_group_weight(pg: str) -> float:
    """Тегло на peer-група в лещата. Default 1.0."""
    return PEER_GROUP_WEIGHT.get(pg, 1.0)


def is_u_shaped(polarity: Any) -> bool:
    """True за U-полярност (лента около цел или около собствената норма)."""
    return isinstance(polarity, tuple) and bool(polarity) and polarity[0] == "U"


def is_opt(polarity: Any) -> bool:
    """True за bounded-optimum полярност `("OPT", lo, hi, s)`."""
    return (
        isinstance(polarity, tuple)
        and len(polarity) == 4
        and polarity[0] == "OPT"
    )


def opt_zone(polarity: Any) -> tuple[float, float, float]:
    """`("OPT", lo, hi, s)` → (lo, hi, s) като числа. Едно място за разопаковането."""
    _, lo, hi, s = polarity
    return float(lo), float(hi), float(s)


def opt_keys() -> list[str]:
    """Ключовете с оптимална зона — В РЕДА на POLARITY.

    ЕДИНСТВЕНИЯТ източник за „кои са бум-сериите": температурният слой се
    извежда оттук, не от собствен списък. В JP v1 е празен списък (фаза 6).
    """
    return [k for k, v in POLARITY.items() if is_opt(v)]
